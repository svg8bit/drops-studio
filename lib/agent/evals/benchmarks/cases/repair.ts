import { defineBenchmarkCase } from "../define-case.ts";
import type { BenchmarkCaseV3 } from "../types.ts";
import { browserFlow } from "./helpers.ts";

interface RepairInput {
  id: string;
  title: string;
  prompt: string;
  fixture: string;
  capability: string;
  artifact: string;
  context: [string, string, ...string[]];
  seed: string;
  focusedCheck: string;
  forbidden: string;
  blocker: string;
  browser?: boolean;
}

function repair(input: RepairInput): BenchmarkCaseV3 {
  return defineBenchmarkCase({
    id: input.id,
    title: input.title,
    suite: "debugging-repair",
    intentKey: `${input.id}-intent`,
    prompt: input.prompt,
    fixtureProject: input.fixture,
    requiredCapabilities: ["sandbox-debugging", input.capability],
    expectedArtifacts: ["reproduced-failure-evidence", input.artifact, "verified-repair-patch"],
    deterministicChecks: [...new Set([
      "project-v2-valid",
      "expected-artifacts",
      input.focusedCheck,
      ...(input.browser ? ["preview-ready", "browser-primary-flow", "no-console-errors"] : []),
    ])],
    ...(input.browser ? { browserFlow: browserFlow(input.id, { axe: input.capability === "accessibility-repair" }) } : {}),
    forbiddenClaims: [input.forbidden],
    hardBlockers: [input.blocker],
    seededFailures: [input.seed],
    maxEstimatedCostUsd: 0.75,
    tags: ["v3", "repair", input.capability],
    category: "repair",
    expectedRoute: "autofix",
    requiredContext: input.context,
    requiresApprovalBoundary: false,
  });
}

