import { defineBenchmarkCase } from "../define-case.ts";
import type { BenchmarkCaseV3 } from "../types.ts";
import { browserFlow } from "./helpers.ts";

interface GenerationInput {
  id: string;
  title: string;
  prompt: string;
  fixture: string;
  capability: string;
  artifact: string;
  context: [string, string, ...string[]];
  forbidden: string;
  blocker: string;
  approval?: boolean;
  providerEvidence?: string[];
  seed?: string;
}

function generation(input: GenerationInput): BenchmarkCaseV3 {
  return defineBenchmarkCase({
    id: input.id,
    title: input.title,
    suite: "new-product-generation",
    intentKey: `${input.id}-intent`,
    prompt: input.prompt,
    fixtureProject: input.fixture,
    requiredCapabilities: ["multi-file-build", input.capability],
    expectedArtifacts: ["project-v2", input.artifact, "production-build-evidence", "browser-flow-evidence"],
    deterministicChecks: [...new Set([
      "project-v2-valid",
      "expected-artifacts",
      "production-build",
      "preview-ready",
      "browser-primary-flow",
      ...(input.providerEvidence ? ["provider-evidence-truth"] : []),
    ])],
    browserFlow: browserFlow(input.id, { click: "button", axe: true }),
    providerEvidenceRequirements: input.providerEvidence,
    forbiddenClaims: [input.forbidden],
    hardBlockers: [input.blocker],
    seededFailures: input.seed ? [input.seed] : [],
    maxEstimatedCostUsd: 1.25,
    tags: ["v3", "generation", input.capability],
    category: "build",
    expectedRoute: "planner",
    requiredContext: input.context,
    requiresApprovalBoundary: input.approval ?? false,
  });
}

