import { defineBenchmarkCase } from "../define-case.ts";
import type { BenchmarkCaseV3, BenchmarkLegacyCategory } from "../types.ts";

interface SecurityInput {
  id: string;
  title: string;
  prompt: string;
  capability: string;
  artifact: string;
  context: [string, string, ...string[]];
  check: string;
  forbidden: string;
  blocker: string;
  seed?: string;
  approval?: boolean;
  expectedBlock?: boolean;
  category?: BenchmarkLegacyCategory;
}

function security(input: SecurityInput): BenchmarkCaseV3 {
  return defineBenchmarkCase({
    id: input.id,
    title: input.title,
    suite: "security-approval",
    intentKey: `${input.id}-intent`,
    prompt: input.prompt,
    fixtureProject: "integration-lab",
    requiredCapabilities: ["security-policy", input.capability],
    expectedArtifacts: ["security-decision-record", input.artifact],
    deterministicChecks: ["project-v2-valid", "expected-artifacts", input.check],
    forbiddenClaims: [input.forbidden],
    hardBlockers: [input.blocker],
    seededFailures: input.seed ? [input.seed] : [],
    legacyDeterministicBlocker: input.expectedBlock ? input.blocker : undefined,
    maxEstimatedCostUsd: 0.35,
    tags: ["v3", "security", input.capability],
    category: input.category ?? "security",
    expectedRoute: "planner",
    requiredContext: input.context,
    requiresApprovalBoundary: input.approval ?? false,
  });
}

