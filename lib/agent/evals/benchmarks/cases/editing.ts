import { defineBenchmarkCase } from "../define-case.ts";
import type { BenchmarkCaseV3, BenchmarkExpectedRoute } from "../types.ts";
import { browserFlow } from "./helpers.ts";

interface EditInput {
  id: string;
  title: string;
  prompt: string;
  fixture: string;
  capability: string;
  artifact: string;
  context: [string, string, ...string[]];
  forbidden: string;
  blocker: string;
  route?: BenchmarkExpectedRoute;
  browser?: boolean;
  seed?: string;
  checks?: string[];
}

function edit(input: EditInput): BenchmarkCaseV3 {
  return defineBenchmarkCase({
    id: input.id,
    title: input.title,
    suite: "existing-project-editing",
    intentKey: `${input.id}-intent`,
    prompt: input.prompt,
    fixtureProject: input.fixture,
    requiredCapabilities: ["project-inspection", input.capability],
    expectedArtifacts: ["project-v2-diff", input.artifact],
    deterministicChecks: [...new Set([
      "project-v2-valid",
      "expected-artifacts",
      "patch-scope",
      ...(input.checks ?? ["typecheck"]),
      ...(input.browser ? ["browser-primary-flow", "no-console-errors"] : []),
    ])],
    ...(input.browser ? { browserFlow: browserFlow(input.id, { axe: input.capability === "accessible-controls" }) } : {}),
    forbiddenClaims: [input.forbidden],
    hardBlockers: [input.blocker],
    seededFailures: input.seed ? [input.seed] : [],
    maxEstimatedCostUsd: 0.45,
    tags: ["v3", "editing", input.capability],
    category: "edit",
    expectedRoute: input.route ?? "quick-edit",
    requiredContext: input.context,
    requiresApprovalBoundary: false,
  });
}

