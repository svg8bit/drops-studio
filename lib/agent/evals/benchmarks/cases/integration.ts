import { defineBenchmarkCase } from "../define-case.ts";
import type { BenchmarkCaseV3, BenchmarkExpectedRoute } from "../types.ts";
import { browserFlow } from "./helpers.ts";

interface IntegrationInput {
  id: string;
  title: string;
  prompt: string;
  capability: string;
  artifact: string;
  context: [string, string, ...string[]];
  evidence: [string, ...string[]];
  forbidden: string;
  blocker: string;
  route?: BenchmarkExpectedRoute;
  approval?: boolean;
  browser?: boolean;
  seed?: string;
  check?: string;
  expectedBlock?: boolean;
}

function integration(input: IntegrationInput): BenchmarkCaseV3 {
  return defineBenchmarkCase({
    id: input.id,
    title: input.title,
    suite: "drops-integrations",
    intentKey: `${input.id}-intent`,
    prompt: input.prompt,
    fixtureProject: "integration-lab",
    requiredCapabilities: ["integration-adapter", input.capability],
    expectedArtifacts: ["typed-integration-evidence", input.artifact],
    deterministicChecks: [...new Set([
      "project-v2-valid",
      "expected-artifacts",
      "provider-evidence-truth",
      input.check ?? "provider-endpoint-documented",
      ...(input.approval ? ["approval-boundary"] : []),
      ...(input.browser ? ["browser-primary-flow", "no-console-errors"] : []),
    ])],
    ...(input.browser ? { browserFlow: browserFlow(input.id) } : {}),
    providerEvidenceRequirements: input.evidence,
    forbiddenClaims: [input.forbidden],
    hardBlockers: [input.blocker],
    legacyDeterministicBlocker: input.expectedBlock ? input.blocker : undefined,
    seededFailures: input.seed ? [input.seed] : [],
    maxEstimatedCostUsd: 0.6,
    tags: ["v3", "integration", input.capability],
    category: "integration",
    expectedRoute: input.route ?? "coder",
    requiredContext: input.context,
    requiresApprovalBoundary: input.approval ?? false,
  });
}

